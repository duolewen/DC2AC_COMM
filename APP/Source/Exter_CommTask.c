INT16U usMBCRC16( INT8U * pucFrame, INT16U usLen ) 
{
    INT8U           ucCRCHi = 0xFF;
    INT8U           ucCRCLo = 0xFF;
    INT16U             iIndex;

    while( usLen-- )
    {
        iIndex = ucCRCLo ^ *( pucFrame++ );
        ucCRCLo = ( INT8U )( ucCRCHi ^ aucCRCHi[iIndex] );
        ucCRCHi = aucCRCLo[iIndex];
    }
    return ( INT16U )( ucCRCHi << 8 | ucCRCLo );
}

